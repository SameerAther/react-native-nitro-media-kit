package com.margelo.nitro.nitromediakit

import android.content.Context
import android.net.Uri
import java.io.File
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL
import java.util.UUID

/** Owns every temporary input and uncommitted output of a single operation. */
internal class MediaJob(private val context: Context) {
    private val scratch = mutableListOf<File>()
    private val outputs = mutableListOf<File>()
    private val resolved = mutableMapOf<String, File>()

    fun output(extension: String): File = File(outputDirectory(context), "${UUID.randomUUID()}.$extension")
        .also { outputs.add(it) }

    fun resolve(source: String): File {
        resolved[source]?.let { return it }
        require(source.isNotBlank()) { "Input URI must not be empty." }
        val uri = Uri.parse(source)
        return when (uri.scheme?.lowercase()) {
            "http", "https" -> {
                val connection = URL(source).openConnection() as HttpURLConnection
                connection.connectTimeout = 30_000
                connection.readTimeout = 30_000
                try {
                    if (connection.responseCode !in 200..299) {
                        throw IOException("Media download failed: HTTP ${connection.responseCode}.")
                    }
                    temporaryFile(uri).also { file ->
                        connection.inputStream.use { input -> file.outputStream().use { input.copyTo(it) } }
                    }
                } finally {
                    connection.disconnect()
                }
            }
            "content" -> temporaryFile(uri).also { file ->
                val input = context.contentResolver.openInputStream(uri)
                    ?: throw IOException("Cannot read content URI.")
                input.use { file.outputStream().use { output -> it.copyTo(output) } }
            }
            null, "file" -> {
                val file = File(if (uri.scheme == null) source else requireNotNull(uri.path))
                require(file.isAbsolute && file.isFile && file.canRead()) { "Input must be a readable absolute file path or URI." }
                file
            }
            else -> throw IllegalArgumentException("Unsupported input URI scheme: ${uri.scheme}.")
        }.also { require(it.length() > 0) { "Input media is empty." }; resolved[source] = it }
    }

    private fun temporaryFile(uri: Uri): File {
        val extension = uri.lastPathSegment?.substringAfterLast('.', "")
            ?.takeIf { it.matches(Regex("[A-Za-z0-9]{1,10}")) } ?: "bin"
        val directory = File(context.cacheDir, "nitro-media-kit/input").apply { mkdirs() }
        return File.createTempFile("input-", ".$extension", directory).also { scratch.add(it) }
    }

    fun finish(success: Boolean) {
        scratch.forEach { it.delete() }
        if (!success) outputs.forEach { it.delete() }
    }

    companion object {
        fun outputDirectory(context: Context): File =
            File(context.cacheDir, "nitro-media-kit/output").apply {
                check(isDirectory || mkdirs()) { "Cannot create media output directory." }
            }

        fun deleteOutput(context: Context, source: String): Boolean {
            val uri = Uri.parse(source)
            require(uri.scheme == null || uri.scheme == "file") { "Expected an output file path or file:// URI." }
            val file = File(if (uri.scheme == null) source else requireNotNull(uri.path)).canonicalFile
            require(file.parentFile == outputDirectory(context).canonicalFile) { "Only files generated by NitroMediaKit can be deleted." }
            require(file.name.matches(Regex("[0-9a-f-]{36}\\.(mp4|jpg|png)"))) { "Invalid generated file name." }
            if (!file.exists()) return false
            check(file.isFile && file.delete()) { "Cannot delete generated file." }
            return true
        }
    }
}
